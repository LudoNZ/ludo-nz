-- Construction QA practice database for the /interview-prep course.
--
-- Load it into an empty database:
--   createdb qa_practice
--   psql -d qa_practice -f interview-prep/db/seed.sql
--
-- Safe to re-run: it drops and recreates every table. All timestamps are
-- relative to now(), so "older than seven days" questions give the same
-- answers whenever you load it. Re-load to reset after experiments.
--
-- Domain notes:
--   * A lot is a defined portion of work on a project (a slab pour, a run of
--     pipe, a block of framing) that gets inspected and signed off.
--   * A checklist template is versioned per company; its checklist_items are
--     the questions. lot_checklists applies one template to one lot.
--   * responses are append-only: a failed item is re-inspected by adding a
--     NEW response row. The current state of an item is its latest response.
--   * A lot_checklist is "signed off" when it has at least one sign_offs row
--     and every one of its sign_offs rows has signed_at set.

BEGIN;

DROP TABLE IF EXISTS sign_offs, photos, responses, lot_checklists, lots,
  checklist_items, checklist_templates, project_members, projects, users, companies CASCADE;

CREATE TABLE companies (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL UNIQUE,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE users (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  bigint NOT NULL REFERENCES companies (id),
  full_name   text NOT NULL,
  email       text NOT NULL UNIQUE,
  role        text NOT NULL CHECK (role IN ('admin', 'project_manager', 'engineer', 'foreman', 'subcontractor')),
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE projects (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  bigint NOT NULL REFERENCES companies (id),
  code        text NOT NULL,
  name        text NOT NULL,
  client_name text,
  status      text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'on_hold', 'completed')),
  started_on  date,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (company_id, code)
);

-- many-to-many: which users work on which projects
CREATE TABLE project_members (
  project_id  bigint NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  user_id     bigint NOT NULL REFERENCES users (id),
  member_role text NOT NULL CHECK (member_role IN ('manager', 'inspector', 'contributor')),
  added_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, user_id)
);

CREATE TABLE lots (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  bigint NOT NULL REFERENCES projects (id),
  code        text NOT NULL,
  description text NOT NULL,
  location    text,
  opened_at   timestamptz NOT NULL DEFAULT now(),
  closed_at   timestamptz,
  UNIQUE (project_id, code)
);

CREATE TABLE checklist_templates (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  bigint NOT NULL REFERENCES companies (id),
  name        text NOT NULL,
  version     integer NOT NULL DEFAULT 1 CHECK (version > 0),
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (company_id, name, version)
);

CREATE TABLE checklist_items (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id    bigint NOT NULL REFERENCES checklist_templates (id),
  position       integer NOT NULL,
  prompt         text NOT NULL,
  response_type  text NOT NULL CHECK (response_type IN ('pass_fail', 'measurement', 'text')),
  requires_photo boolean NOT NULL DEFAULT false,
  is_hold_point  boolean NOT NULL DEFAULT false,
  UNIQUE (template_id, position)
);

-- a template applied to a lot
CREATE TABLE lot_checklists (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_id      bigint NOT NULL REFERENCES lots (id),
  template_id bigint NOT NULL REFERENCES checklist_templates (id),
  assigned_to bigint REFERENCES users (id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (lot_id, template_id)
);

-- append-only: re-inspections add rows, the latest row per item wins
CREATE TABLE responses (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_checklist_id  bigint NOT NULL REFERENCES lot_checklists (id),
  checklist_item_id bigint NOT NULL REFERENCES checklist_items (id),
  result            text CHECK (result IN ('pass', 'fail', 'na')),
  measured_value    numeric,
  notes             text,
  responded_by      bigint NOT NULL REFERENCES users (id),
  responded_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE photos (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  response_id  bigint NOT NULL REFERENCES responses (id),
  storage_key  text NOT NULL UNIQUE,
  size_bytes   integer CHECK (size_bytes > 0),
  taken_at     timestamptz,
  uploaded_by  bigint NOT NULL REFERENCES users (id),
  uploaded_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sign_offs (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_checklist_id bigint NOT NULL REFERENCES lot_checklists (id),
  signer_role      text NOT NULL CHECK (signer_role IN ('foreman', 'engineer')),
  requested_by     bigint NOT NULL REFERENCES users (id),
  requested_at     timestamptz NOT NULL DEFAULT now(),
  signed_by        bigint REFERENCES users (id),
  signed_at        timestamptz,
  CHECK ((signed_by IS NULL) = (signed_at IS NULL)),
  CHECK (signed_at IS NULL OR signed_at >= requested_at),
  UNIQUE (lot_checklist_id, signer_role)
);

